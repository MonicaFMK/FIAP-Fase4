import streamlit as st
import pandas as pd

dados = pd.read_csv('https://raw.githubusercontent.com/MonicaFMK/FIAP-Fase4/refs/heads/main/Obesity-formatado-LIMPO.csv')

st.write('# DADOS OBESITY')

